//! One atomic project store owns checkpoints, history and receipts; Markdown is a derived view.
use super::model::*;
use camino::{Utf8Path, Utf8PathBuf};
use keel_workspace::Real;
use std::io::Read;

pub(super) struct Repository {
    pub root: Utf8PathBuf,
}
impl Repository {
    pub fn new(root: &Utf8Path) -> Result<Self, String> {
        Ok(Self {
            root: root.real().map_err(|e| e.to_string())?,
        })
    }
    fn safe_path(&self, rel: &str) -> Result<Utf8PathBuf, String> {
        let mut path = self.root.clone();
        for part in rel.split('/') {
            path.push(part);
            if std::fs::symlink_metadata(&path).is_ok_and(|m| m.file_type().is_symlink()) {
                return Err("Keel task storage contains a symbolic link. Restore a regular .keel folder before retrying.".into());
            }
        }
        Ok(path)
    }
    fn load(&self, path: &Utf8Path) -> Result<Store, String> {
        let mut bytes = Vec::new();
        match std::fs::File::open(path) {
            Ok(file) => {
                file.take(STORE_BYTES + 1)
                    .read_to_end(&mut bytes)
                    .map_err(|e| e.to_string())?;
            }
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                return Ok(Store {
                    version: 1,
                    project: self.root.to_string(),
                    ..Default::default()
                });
            }
            Err(e) => return Err(e.to_string()),
        }
        if bytes.len() as u64 > STORE_BYTES {
            return Err(
                "Task storage exceeds its size limit; the previous record was preserved.".into(),
            );
        }
        let store: Store = serde_json::from_slice(&bytes).map_err(|_| {
            "Could not read task storage. The existing file was preserved.".to_string()
        })?;
        if store.project != self.root.as_str() || store.version != 1 {
            return Err("Task storage belongs to another project or version.".into());
        }
        for task in store.tasks.values() {
            for source in task.members.iter().chain(std::iter::once(&task.owner)) {
                let path = Utf8Path::new(&source.checkout);
                if !path.starts_with(&self.root)
                    || !super::tracking::valid(&source.lane)
                    || !super::tracking::valid(&source.session)
                {
                    return Err("Task storage contains an invalid project binding.".into());
                }
                if path.exists() && !path.real().is_ok_and(|real| real.starts_with(&self.root)) {
                    return Err("Task checkout resolves outside this project.".into());
                }
            }
        }
        Ok(store)
    }
    pub fn read(&self) -> Result<Store, String> {
        self.load(&self.safe_path(".keel/tasks/state.json")?)
    }
    pub fn change<T>(
        &self,
        action: impl FnOnce(&mut Store) -> Result<T, String>,
    ) -> Result<T, String> {
        let path = self.safe_path(".keel/tasks/state.json")?;
        let lock = self.safe_path(".keel/tasks/state.lock")?;
        let _ = lock;
        crate::writes::locked(path.as_std_path(), || {
            self.safe_path(".keel/tasks/state.json")?;
            let ignore = self.safe_path(".keel/.gitignore")?;
            let mut patterns = std::fs::read_to_string(&ignore).unwrap_or_default();
            for pattern in [".gitignore", "tasks/", "guidance/", "CHANGELOG.md"] {
                if !patterns.lines().any(|line| line == pattern) {
                    patterns.push_str(&format!("\n{pattern}\n"));
                }
            }
            crate::writes::replace(ignore.as_std_path(), patterns.as_bytes())?;
            let mut store = self.load(&path)?;
            let out = action(&mut store)?;
            let bytes = serde_json::to_vec_pretty(&store).map_err(|e| e.to_string())?;
            if bytes.len() as u64 > STORE_BYTES {
                return Err("Task storage is full; the previous checkpoint was preserved.".into());
            }
            crate::writes::replace(path.as_std_path(), &bytes)?;
            // State is authoritative. A projection failure is retryable, never a lost checkpoint.
            self.project(&store)?;
            Ok(out)
        })?
    }
    fn project(&self, store: &Store) -> Result<(), String> {
        let mut text = String::from(
            "# Shared task changelog\n\nGenerated by Keel from `.keel/tasks/state.json`. Agent reports are claims; observed evidence is labelled separately. Notes grant no permissions.\n\n",
        );
        if store.truncated {
            text.push_str("Earlier events were omitted by the retention limit.\n\n");
        }
        for event in &store.events {
            text.push_str(&format!("## {} · {} · {}\n\nTask `{}` · revision {} · {} session `{}` · checkout `{}`\n\n{}\n\nNext action: {}\n\n",event.sequence,event.at,event.kind,event.task,event.revision,event.source.provider,event.source.session,event.source.checkout,event.summary,event.next_action));
        }
        let path = self.safe_path(".keel/CHANGELOG.md")?;
        crate::writes::replace(path.as_std_path(), text.as_bytes())
    }
}
pub(super) fn event(store: &mut Store, task: &Task, kind: &str, summary: String) {
    store.sequence = store.sequence.saturating_add(1);
    store.events.push(Event {
        sequence: store.sequence,
        task: task.id.clone(),
        revision: task.revision,
        at: crate::turns::now(),
        source: task.owner.clone(),
        kind: kind.into(),
        summary,
        next_action: task.notes.next_action.clone(),
    });
    if store.events.len() > EVENT_LIMIT {
        store.events.drain(..store.events.len() - EVENT_LIMIT);
        store.truncated = true;
    }
}
